from rest_framework import serializers
from cars.models import Car
from users.models import User
from cars.validators import validate_plate_number
from core.exceptions import APIError, CarsError

class CarSerializer(serializers.ModelSerializer):
    id = serializers.IntegerField(required=False, read_only=True)
    plate = serializers.CharField()
    model = serializers.CharField()
    color = serializers.CharField()
    image = serializers.ImageField(required=False, read_only=True)
    
    class Meta:
        model = Car
        fields = ["id", "plate", "model", "color", "image", "is_active"]
        read_only_fields = ["id", "image"] # Image is read-only, generated by backend

    def validate_plate(self, value):
        instance = self.instance
        validate_plate_number(value, instance)
        return value